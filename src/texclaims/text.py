"""Getting comparable text out of a PDF and out of LaTeX source.

Each normalisation here exists because a check went blind without it:

* pdftotext returns typeset ligatures ("Con\\ufb02ict"), so a search for "Conflict" misses.
* Classes that set maths in STIX make an inline $p$ come out as U+1D45D, not "p", so every check
  that looks for a symbol next to its value stops matching when the document class changes.
* pdftotext emits tables column by column, so table cells are read from the .tex, never the PDF.
* Raw LaTeX makes "64%" fail against "$64\\%$": prose read from source is normalised toward what
  the PDF renders, so the same needle works on both.
* A rendered PDF also contains the generated tables, so a value taken from a table and searched
  for in the PDF finds the table and cannot fail. Prose checks read hand-written sources only.
"""
from __future__ import annotations

import glob
import os
import re
import shutil
import subprocess
import unicodedata
from typing import Iterable

LIGATURES = str.maketrans({"\ufb00": "ff", "\ufb01": "fi", "\ufb02": "fl",
                           "\ufb03": "ffi", "\ufb04": "ffl", "\ufb05": "st", "\ufb06": "st"})

_COMMENT = re.compile(r"(?<!\\)%.*")


def demath(t: str) -> str:
    """Fold Unicode mathematical alphanumerics (U+1D400-U+1D7FF) back to ASCII letters/digits."""
    out = []
    for ch in t:
        if 0x1D400 <= ord(ch) <= 0x1D7FF:
            name = unicodedata.name(ch, "")
            base = name.split()[-1] if name else ""
            if " DIGIT " in name and base in _DIGITS:
                ch = str(_DIGITS.index(base))
            elif len(base) == 1:
                ch = base.lower() if " SMALL " in name else base
        out.append(ch)
    return "".join(out)


_DIGITS = ["ZERO", "ONE", "TWO", "THREE", "FOUR", "FIVE", "SIX", "SEVEN", "EIGHT", "NINE"]


def _pdftotext(path: str, *args: str) -> str:
    if not shutil.which("pdftotext"):
        raise RuntimeError("pdftotext (poppler-utils) is required to read PDFs")
    if not os.path.exists(path):
        raise FileNotFoundError(path)
    out = subprocess.run(["pdftotext", *args, path, "-"], capture_output=True, text=True)
    return out.stdout.translate(LIGATURES)


def pdf_text(path: str) -> str:
    """Rendered text of a PDF as one whitespace-squeezed stream."""
    return demath(" ".join(_pdftotext(path).split()))


def pdf_lines(path: str) -> str:
    """Layout-preserving text, one rendered line per line.

    In the flat stream a figure's tick label can land between two words it is nowhere near on
    the page. Match against this when a number is read from its neighbouring words."""
    lay = demath(_pdftotext(path, "-layout"))
    return "\n".join(" ".join(ln.split()) for ln in lay.split("\n"))


def strip_comments(t: str) -> str:
    """Drop TeX comments (an unescaped % to end of line)."""
    return "\n".join(_COMMENT.sub("", ln) for ln in t.split("\n"))


def detex(t: str) -> str:
    """Approximate rendered text of a TeX fragment.

    Commands with one argument keep the argument; \\cite, \\ref and \\label disappear; escapes
    lose their backslash; maths delimiters go; \\pm becomes the sign it prints."""
    t = strip_comments(t)
    t = re.sub(r"\\(?:cite[pt]?|ref|eqref|autoref|cref|Cref|label)\*?(?:\[[^\]]*\])*\{[^{}]*\}", "", t)
    t = t.replace("\\pm", "\u00b1").replace("\\times", "\u00d7").replace("\\%", "%")
    t = t.replace("\\_", "_").replace("\\&", "&").replace("\\#", "#").replace("\\$", "\x00")
    t = t.replace("{,}", ",").replace("\\,", " ").replace("~", " ")
    t = t.replace("$", "").replace("\x00", "$")
    for _ in range(3):  # nested one-argument commands
        t = re.sub(r"\\(?:texttt|textbf|textit|emph|textsc|textrm|mathrm|mathbf|text|url|mbox)"
                   r"\{([^{}]*)\}", r"\1", t)
    t = re.sub(r"\\[A-Za-z]+\*?(\[[^\]]*\])?", " ", t)
    t = t.replace("{", "").replace("}", "").replace("``", '"').replace("''", '"')
    t = t.replace("---", "\u2014").replace("--", "\u2013")
    return " ".join(t.split())


def is_generated(path: str, prefixes: Iterable[str] = ("gen_", "tab_"),
                 marker: str = "generated by") -> bool:
    """A source file is generated if its name has a generator prefix or its head says so."""
    if os.path.basename(path).startswith(tuple(prefixes)):
        return True
    with open(path, encoding="utf-8") as fh:
        return marker.lower() in fh.read(400).lower()


def prose(paths: Iterable[str] | str, *, include_generated: bool = False,
          prefixes: Iterable[str] = ("gen_", "tab_")) -> str:
    """Hand-written prose of the given .tex files (or a glob), normalised toward the PDF."""
    if isinstance(paths, str):
        paths = sorted(glob.glob(paths))
    parts = []
    for p in paths:
        if not include_generated and is_generated(p, prefixes):
            continue
        with open(p, encoding="utf-8") as fh:
            parts.append(fh.read())
    return detex("\n".join(parts))


def sentences(text: str) -> list[str]:
    """Split on a full stop followed by whitespace; a stop between digits is a decimal point."""
    return [s for s in re.split(r"(?<!\d)\.\s+|(?<=\d)\.\s+(?=[A-Z])", text.replace("\n", " ")) if s]


def section(raw: str, start: str, *stops: str) -> str | None:
    """Text of the block that starts at the line equal to `start` up to the first line equal to
    one of `stops`, digit-only lines (page numbers) dropped. None if `start` is absent."""
    lines = [ln.strip() for ln in raw.split("\n")]
    if start not in lines:
        return None
    i = lines.index(start) + 1
    j = next((k for k in range(i, len(lines)) if lines[k] in stops), len(lines))
    return " ".join(" ".join(ln for ln in lines[i:j] if ln and not ln.isdigit()).split())


def has(text: str, *variants: str) -> bool:
    """Whether any of the renderings occurs in `text`."""
    return any(v in text for v in variants)
