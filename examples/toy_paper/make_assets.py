"""Write the generated table from data/results.csv. Bold = q < 0.05 against the baseline."""
import csv
import os

HERE = os.path.dirname(os.path.abspath(__file__))
rows = list(csv.DictReader(open(os.path.join(HERE, "data", "results.csv"), encoding="utf-8")))
lines = ["% generated by make_assets.py -- do not edit",
         "\\begin{tabular}{lcc}", "\\toprule", "Model & F1 & $q$ \\\\", "\\midrule"]
for r in rows:
    f1 = f"{float(r['f1']):.3f}"
    if float(r["q_value"]) < 0.05:
        f1 = f"\\textbf{{{f1}}}"
    lines.append(f"{r['model']} & {f1} & {float(r['q_value']):.3f} \\\\")
lines += ["\\bottomrule", "\\end{tabular}"]
with open(os.path.join(HERE, "sections", "tab_results.tex"), "w", encoding="utf-8") as fh:
    fh.write("\n".join(lines) + "\n")
