from texclaims import text as T


def test_demath_folds_math_italic_and_digits():
    assert T.demath("\U0001D45D = 0.03") == "p = 0.03"          # MATHEMATICAL ITALIC SMALL P
    assert T.demath("\U0001D400\U0001D7CE") == "A0"           # bold capital A, bold digit zero
    assert T.demath("\U0001D6FC") == "\U0001D6FC"              # Greek alpha left alone


def test_ligatures_fold():
    assert "Con\ufb02ict of \ufb01ndings".translate(T.LIGATURES) == "Conflict of findings"


def test_detex_normalises_toward_the_pdf():
    src = r"F1 of $0.968 \pm 0.018$ on 64\% of rows~\cite{x}, see Table~\ref{tab:a}. % note"
    assert T.detex(src) == "F1 of 0.968 \u00b1 0.018 on 64% of rows , see Table ."


def test_detex_keeps_arguments_of_formatting_commands():
    assert T.detex(r"\textbf{\emph{best}} model \texttt{rf\_300}") == "best model rf_300"


def test_prose_skips_generated_files(tmp_path):
    (tmp_path / "01_intro.tex").write_text("We report 0.85.", encoding="utf-8")
    (tmp_path / "tab_main.tex").write_text("RF & 0.85 \\\\", encoding="utf-8")
    (tmp_path / "02_res.tex").write_text("% generated by make_assets.py\nX", encoding="utf-8")
    assert T.prose(str(tmp_path / "*.tex")) == "We report 0.85."
    assert "RF" in T.prose(str(tmp_path / "*.tex"), include_generated=True)


def test_sentences_do_not_split_decimals():
    assert T.sentences("AUC was 0.95. Then it fell. F1 0.8.") == ["AUC was 0.95", "Then it fell", "F1 0.8."]


def test_section_slices_between_headings():
    raw = "Intro\nfoo\n3\nResults\nbar baz\nDiscussion\nqux"
    assert T.section(raw, "Results", "Discussion") == "bar baz"
    assert T.section(raw, "Missing") is None
